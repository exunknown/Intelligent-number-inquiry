SET NAMES utf8mb4;
USE meta;

CREATE TABLE IF NOT EXISTS query_audit
(
    id           VARCHAR(36) PRIMARY KEY,
    request_id   VARCHAR(64),
    created_at   DATETIME NOT NULL,
    user_id      VARCHAR(255) NOT NULL,
    username     VARCHAR(255),
    roles        JSON NOT NULL,
    policy_version BIGINT UNSIGNED NOT NULL,
    allowed_department_ids JSON NOT NULL,
    authz_outcome VARCHAR(32) NOT NULL,
    query_text   TEXT NOT NULL,
    query_mode   VARCHAR(16),
    route_reason VARCHAR(64),
    metric_query JSON,
    cube_query   JSON,
    sql_text     TEXT,
    normalized_sql TEXT,
    executed_sql TEXT,
    sql_policy_outcome VARCHAR(32),
    sql_rejection_reason VARCHAR(64),
    sql_estimated_rows BIGINT,
    sql_query_cost DOUBLE,
    result_row_count INT,
    result_bytes BIGINT,
    result_truncated BOOLEAN,
    sql_execution_duration_ms INT,
    llm_call_count INT NOT NULL DEFAULT 0,
    embedding_call_count INT NOT NULL DEFAULT 0,
    llm_input_tokens INT,
    llm_output_tokens INT,
    llm_cost_units DOUBLE,
    outcome      VARCHAR(32) NOT NULL,
    error_code   VARCHAR(64),
    verified     BOOLEAN,
    duration_ms  INT NOT NULL,
    INDEX idx_query_audit_user_created (user_id, created_at),
    INDEX idx_query_audit_policy_created (policy_version, created_at)
);
